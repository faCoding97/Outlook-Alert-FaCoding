#!/usr/bin/env python3
"""Package a published Windows app with Microsoft's MSIX SDK, then Authenticode-sign it.

Private signing inputs stay in Packaging/signing-private; never distribute them.
The final package must also pass Windows Add-AppxPackage verification at install.
"""
from __future__ import annotations
import argparse, hashlib, json, shutil, subprocess, zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

HERE = Path(__file__).resolve().parent
TOOLS = HERE / 'toolchain'
MAKEMSIX = TOOLS / 'msix-build/bin/makemsix'
SIGN = TOOLS / 'osslsigncode-build/osslsigncode'
KEY = HERE / 'signing-private/publisher.key'
PEM = HERE / 'signing-private/publisher.pem'
CER = HERE / 'OutlookAlert-Publisher.cer'


def run(*args: str | Path) -> None:
    print('+', ' '.join(str(a) for a in args), flush=True)
    subprocess.run([str(a) for a in args], check=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--publish', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    publish, output = args.publish.resolve(), args.output.resolve()
    if not (publish / 'OutlookAlert.exe').is_file():
        raise SystemExit('Published OutlookAlert.exe not found; refusing to package.')
    for required in (MAKEMSIX, SIGN, KEY, PEM, CER):
        if not required.is_file():
            raise SystemExit(f'Required build/signing input missing: {required}')
    output.parent.mkdir(parents=True, exist_ok=True)
    stage = HERE / 'stage'
    if stage.exists():
        shutil.rmtree(stage)
    shutil.copytree(publish, stage)
    shutil.copy2(HERE / 'Package.appxmanifest', stage / 'AppxManifest.xml')
    shutil.copytree(HERE / 'Assets', stage / 'Assets', dirs_exist_ok=True)
    # Avoid packaging any debug symbols generated by the compiler.
    for item in stage.rglob('*.pdb'):
        item.unlink()
    for forbidden in ('*.key', '*.pfx', '*.pem'):
        if list(stage.rglob(forbidden)):
            raise SystemExit('Refusing to package private certificate material.')
    unsigned = output.with_suffix('.unsigned.msix')
    for item in (unsigned, output):
        if item.exists(): item.unlink()
    run(MAKEMSIX, 'pack', '-d', stage, '-p', unsigned)
    run(SIGN, 'sign', '-certs', PEM, '-key', KEY, '-h', 'sha256', '-n', 'Outlook Alert', '-in', unsigned, '-out', output)
    run(SIGN, 'verify', '-CAfile', PEM, '-in', output)
    # The MSIX SDK must fully validate all XML, ZIP, and block hashes when unpacking.
    # -ac allows our explicit development publisher on Linux; Windows installer
    # separately pins the certificate and trusts its public leaf before installation.
    unpack = HERE / 'validation-unpack'
    if unpack.exists(): shutil.rmtree(unpack)
    run(MAKEMSIX, 'unpack', '-ac', '-p', output, '-d', unpack)
    with zipfile.ZipFile(output) as z:
        if z.testzip() is not None:
            raise SystemExit('ZIP CRC validation failed.')
        if 'AppxSignature.p7x' not in z.namelist():
            raise SystemExit('Package signature missing.')
        manifest = ET.fromstring(z.read('AppxManifest.xml'))
        identity = manifest.find('{http://schemas.microsoft.com/appx/manifest/foundation/windows10}Identity')
        assert identity is not None
        assert identity.attrib['Name'] == 'Faraz.OutlookAlert'
        assert identity.attrib['Publisher'] == 'CN=Faraz Outlook Alert'
        if z.read('OutlookAlert.exe') != (publish / 'OutlookAlert.exe').read_bytes():
            raise SystemExit('Published executable changed while packaging.')
        count = len(z.namelist())
    metadata = {
        'package_name': 'Faraz.OutlookAlert',
        'application_id': 'App',
        'publisher': 'CN=Faraz Outlook Alert',
        'package_version': identity.attrib['Version'],
        'architecture': 'x64',
        'package_size_bytes': output.stat().st_size,
        'package_sha256': hashlib.sha256(output.read_bytes()).hexdigest().upper(),
        'certificate_sha256': hashlib.sha256(CER.read_bytes()).hexdigest().upper(),
        'certificate_thumbprint_sha1': hashlib.sha1(CER.read_bytes()).hexdigest().upper(),
        'package_entry_count': count,
        'validation': 'Microsoft MSIX SDK pack+unpack schema/block validation; osslsigncode signature verification; ZIP CRC; executable byte comparison',
        'windows_installation_tested': False,
    }
    output.with_suffix('.metadata.json').write_text(json.dumps(metadata, indent=2) + '\n')
    print(json.dumps(metadata, indent=2))

if __name__ == '__main__':
    main()
